"""Measurement I pre-registration gates: results, peak GPU memory, k-limit byte equality, GPU-time estimate.

python3 pre_i.py RUN --output JSON --tables MD
Standard library only. Per gate: adapter exit status (0 for u4m), oracle check, nvidia-smi peak MiB (gpu_memory.py)
and, for GPUSparse, the torch allocator peak from the adapter's validation report; median per-query wall time of the
measured round; process duration. Estimate for the registered timing (3 processes x (3 + 20 rounds) per cell, GPUSparse
U64 and FP32 where exact, u4m): per process = gate duration (start-up, JIT, index load, 2 rounds) + 21 x 1.25 x (sum of
the measured round's query_wall_ms) + 15 s.
"""
import argparse, csv, json, statistics
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("run"); ap.add_argument("--output", required=True); ap.add_argument("--tables", required=True)
    a = ap.parse_args(); run = Path(a.run)
    mem = json.loads((run / "analysis/gpu-memory.json").read_text())
    proc = {r[0]: r for r in csv.reader(open(run / "logs/processes.tsv"), delimiter="\t")}
    cells = {}
    for tag, impl, k, status in csv.reader(open(run / "logs/cell-status.tsv"), delimiter="\t"):
        rows = [r for r in csv.DictReader(open(run / "raw" / (tag + ".csv"))) if r["phase"] == "measured"] if (run / "raw" / (tag + ".csv")).exists() else []
        walls = [float(r["query_wall_ms"]) for r in rows]
        v = run / "raw" / (tag + "-validation.json")
        val = json.loads(v.read_text()) if v.exists() else {}
        comp = run / "analysis" / ("compare-%s.json" % tag)
        dur = float(proc[tag][4]) - float(proc[tag][3])
        cells[tag] = dict(impl=impl, k=int(k[1:]), status=status, exact=status == "0" and comp.exists() and json.loads(comp.read_text())["success"],
                          median_query_wall_ms=statistics.median(walls) if walls else None, process_seconds=dur,
                          est_timing_process_seconds=dur + 21 * 1.25 * sum(walls) / 1000 + 15 if walls else None,
                          peak_gpu_mib=mem.get(tag, {}).get("peak_used_mib"), torch_allocator_peak_bytes=val.get("torch_allocator_peak_bytes"),
                          adapter_success=val.get("success"))
    eq = [dict(variant=r[0], k=int(r[1][1:]), result=r[2]) for r in csv.reader(open(run / "logs/klimit-byte-equality.tsv"), delimiter="\t")]
    fp32_exact = {c["k"] for c in cells.values() if c["impl"] in ("f32", "f32k") and c["exact"] and (c["k"] == 1000 or any(e["variant"] == "f32" and e["k"] == c["k"] and e["result"] == "identical" for e in eq))}
    timing = {10: ["u64", "f32", "u4m"], 100: ["u64", "f32", "u4m"], 1000: ["u64k", "f32k", "u4m"]}
    est = lambda with_f32: sum(3 * cells["gate-%s-k%d" % (i, k)]["est_timing_process_seconds"] for k, imps in timing.items() for i in imps if not i.startswith("f32") or (with_f32 and k in fp32_exact)) / 60
    out = dict(cells=cells, klimit_byte_equality=eq, fp32_exact_at_k=sorted(fp32_exact), estimate_minutes=dict(with_fp32_where_exact=est(True), without_fp32=est(False)))
    md = ["# Measurement I gates (generated by pre_i.py)", "", "| gate | k | status | exact | median ms (1 round) | process s | peak GPU MiB (nvidia-smi) | torch allocator peak MiB |", "|---|---|---|---|---|---|---|---|"]
    for t, c in cells.items():
        md.append("| %s | %d | %s | %s | %s | %.0f | %s | %s |" % (t, c["k"], c["status"], "yes" if c["exact"] else "NO", "%.3f" % c["median_query_wall_ms"] if c["median_query_wall_ms"] else "–", c["process_seconds"], c["peak_gpu_mib"], "%.0f" % (c["torch_allocator_peak_bytes"] / 2**20) if c["torch_allocator_peak_bytes"] else "–"))
    md += ["", "k-limit copies vs original adapters (top.tsv bytes): " + "; ".join("%s k=%d %s" % (e["variant"], e["k"], e["result"]) for e in eq),
           "", "FP32 exact at k: %s" % (", ".join(map(str, sorted(fp32_exact))) or "none"),
           "", "GPU-time estimate for the registered timing: %.0f min with FP32 where exact; %.0f min without FP32." % (out["estimate_minutes"]["with_fp32_where_exact"], out["estimate_minutes"]["without_fp32"])]
    Path(a.output).write_text(json.dumps(out, indent=2) + "\n"); Path(a.tables).write_text("\n".join(md) + "\n")
    print(json.dumps(out["estimate_minutes"]), out["fp32_exact_at_k"])


if __name__ == "__main__":
    main()
