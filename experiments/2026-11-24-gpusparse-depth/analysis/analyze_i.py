"""Measurement I analysis: u4m against the GPUSparse canonical adaptation (U64, guarded FP32), full collection, batch 1.

python3 analyze_i.py RUN --output JSON --tables MD
Reuses experiments/2026-11-22-range-v3-tune/analysis/analyze_timing_e.py (per-process per-query medians of
query_wall_ms; crossed bootstrap over processes and queries, 10,000 draws) with the registered seed 20261126.
Per cell: pooled median, p95, p99 over the 3 x 500 per-process query medians; u4m / GPUSparse at the same k:
geometric mean of paired (process round p, query) ratios with a 95% interval. Peak GPU MiB: max over the cell's
processes (nvidia-smi, gpu_memory.py). Cross-session checks (descriptive): GPUSparse U64 k=10 vs 6.890 ms, FP32 k=10
vs 6.008 ms (published team baselines); u4m vs Measurement F 0.403 / 0.455 / 0.833 ms.
GPUSparse's per-query time includes its Python host path (query padding and upload through result copy and
original-ID mapping), as in the team's earlier comparisons; u4m's is its C++ host loop.
"""
import argparse, json, math, statistics, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "2026-11-22-range-v3-tune" / "analysis"))
import analyze_timing_e as E   # noqa: E402

E.SEED = 20261126
NAME = {"u64": "GPUSparse U64 (canonical)", "u64k": "GPUSparse U64 (k-limit variant)", "f32": "GPUSparse guarded FP32 (canonical)", "f32k": "GPUSparse guarded FP32 (k-limit variant)", "u4m": "u4m (W=4096)"}
PUBLISHED = {("u64", 10): 6.890, ("f32", 10): 6.008, ("u4m", 10): 0.4031, ("u4m", 100): 0.4548, ("u4m", 1000): 0.8329}


def q(v, p):
    v = sorted(v); pos = p * (len(v) - 1); lo = int(pos); hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("run"); ap.add_argument("--output", required=True); ap.add_argument("--tables", required=True)
    a = ap.parse_args(); run = Path(a.run); boot = E.Boot(500)
    mem = json.loads((run / "analysis/gpu-memory.json").read_text())
    timed = {int(l.split("\t")[0][1:]): l.split("\t")[1].split() for l in (run / "logs/timed-cells.tsv").read_text().splitlines()}
    out = dict(bootstrap_seed=E.SEED, k={}, label="calibration queries only (500), after the freeze; one cuda5 session")
    md = ["# Measurement I tables (generated by analyze_i.py)", "", "Calibration only, after the freeze. Per-query wall latency, batch 1; u4m / it = geometric mean of paired ratios, crossed bootstrap (seed %d)." % E.SEED]
    for k, impls in timed.items():
        logs, cells = {}, {}
        for i in impls:
            rows = []
            for p in range(3):
                _, wall, _ = E.medians(run / "raw" / ("timing-k%d-r%d-%s.csv" % (k, p, i)), 500, 20, 3)
                rows.append([math.log(x) for x in wall])
            logs[i] = rows; flat = [math.exp(x) for r in rows for x in r]
            peaks = [mem.get("timing-k%d-r%d-%s" % (k, p, i), {}).get("peak_used_mib") for p in range(3)]
            cells[i] = dict(name=NAME[i], median_ms=statistics.median(flat), p95_ms=q(flat, .95), p99_ms=q(flat, .99), peak_gpu_mib=max((x for x in peaks if x), default=None))
        for i in impls:
            if i != "u4m":
                cells[i]["u4m_over_it"] = boot.ratio(logs["u4m"], logs[i])
        for i in impls:
            ref = PUBLISHED.get((i.rstrip("k") if i != "u4m" else i, k))
            if ref:
                cells[i]["cross_session"] = dict(published_ms=ref, ratio=cells[i]["median_ms"] / ref)
        out["k"][str(k)] = cells
        md += ["", "## k = %d" % k, "", "| implementation | pooled median ms (p95 / p99) | u4m / it [95%] | peak GPU MiB |", "|---|---|---|---|"]
        for i in impls:
            c = cells[i]; r = c.get("u4m_over_it")
            md.append("| %s | %.3f (%.3f / %.3f) | %s | %s |" % (c["name"], c["median_ms"], c["p95_ms"], c["p99_ms"], "%.3f [%.3f, %.3f]" % (r["estimate"], *r["interval_95"]) if r else "–", c["peak_gpu_mib"]))
    md += ["", "## Cross-session checks (descriptive)", ""]
    for k, cells in out["k"].items():
        for i, c in cells.items():
            if "cross_session" in c:
                md.append("- %s, k=%s: %.4f ms vs published %.4f ms (ratio %.3f)" % (c["name"], k, c["median_ms"], c["cross_session"]["published_ms"], c["cross_session"]["ratio"]))
    Path(a.output).write_text(json.dumps(out, indent=2) + "\n"); Path(a.tables).write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
