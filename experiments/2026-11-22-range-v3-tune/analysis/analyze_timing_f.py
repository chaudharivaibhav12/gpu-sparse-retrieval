"""Paired statistics for Measurement F (run_timing_f.sh): every cell against ctrl at the full collection.

python3 analyze_timing_f.py RUN --cells v3-4-default ctrl [prunetm] --output JSON --tables MD
    [--queries 500 --rounds 20 --warmups 3]

Standard library only; reuses analyze_timing_e.py's per-process query medians and crossed
bootstrap, with a new seed (20261123). Per process: median query_wall_ms of each query over the
measured rounds; processes paired by index within a k set; ratio X/ctrl = geometric mean of the
3 x 500 paired ratios; crossed bootstrap (processes and queries resampled independently), 10,000
draws, 95% percentile interval. Calibration queries only, after the freeze (the held-out queries
were used in PR #27): the results are not held-out evaluations.
"""
import argparse, json, math, statistics, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_timing_e as E   # noqa: E402

E.SEED = 20261123
KS = (10, 100, 1000)
NAME = {"v3-4-default": ("u4m (range v3-4, default build)", 4096), "ctrl": ("ctrl (range V2-5)", 1024), "prunetm": ("prune-tm (pruned, 64 seeds)", 256)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run"); ap.add_argument("--cells", nargs="+", required=True)
    ap.add_argument("--output", required=True); ap.add_argument("--tables", required=True)
    ap.add_argument("--queries", type=int, default=500); ap.add_argument("--rounds", type=int, default=20); ap.add_argument("--warmups", type=int, default=3)
    a = ap.parse_args()
    run = Path(a.run); boot = E.Boot(a.queries)
    out = dict(bootstrap_seed=E.SEED, bootstrap_draws=E.DRAWS, processes=E.P, queries=a.queries, cells=a.cells,
               qualification="Full collection (8,841,823 passages); 500 calibration queries only; after the freeze (held-out queries used in PR #27); conditional on this cuda5 session and three processes per cell. Ratios below 1 favour the numerator.",
               k={})
    md = ["# Measurement F tables (generated by analyze_timing_f.py)", "",
          "Full collection, 500 calibration queries, wall latency per query; ratio = geometric mean of paired query/process ratios to ctrl, crossed bootstrap 95%% interval (%d draws, seed %d). Calibration only, after the freeze." % (E.DRAWS, E.SEED), ""]
    for k in KS:
        logs, desc = {}, {}
        order = None
        for c in a.cells:
            rows, gpu = [], []
            for p in range(E.P):
                qids, wall, g = E.medians(run / "raw" / ("timing-k%d-r%d-%s.csv" % (k, p, c)), a.queries, a.rounds, a.warmups)
                assert order is None or qids == order; order = qids
                rows.append([math.log(x) for x in wall]); gpu += g
            logs[c] = rows
            flat = [math.exp(x) for r in rows for x in r]
            desc[c] = dict(pooled_median_ms=statistics.median(flat), pooled_median_gpu_span_ms=statistics.median(gpu),
                           process_medians_ms=[statistics.median(math.exp(x) for x in r) for r in rows])
        con = {"%s / ctrl" % c: boot.ratio(logs[c], logs["ctrl"]) for c in a.cells if c != "ctrl"}
        if "prunetm" in a.cells:
            con["v3-4-default / prunetm"] = boot.ratio(logs["v3-4-default"], logs["prunetm"])
        out["k"][str(k)] = dict(descriptive=desc, contrasts=con)
        md += ["## k = %d" % k, "", "| implementation | W | pooled median ms | GPU span median ms | ratio to ctrl [95%] |", "|---|---|---|---|---|"]
        for c in a.cells:
            r = con.get("%s / ctrl" % c)
            md.append("| %s | %d | %.4f | %.4f | %s |" % (NAME[c][0], NAME[c][1], desc[c]["pooled_median_ms"], desc[c]["pooled_median_gpu_span_ms"],
                      "1 (reference)" if c == "ctrl" else "%.3f [%.3f, %.3f]" % (r["estimate"], *r["interval_95"])))
        if "prunetm" in a.cells:
            r = con["v3-4-default / prunetm"]
            md.append("\nu4m / prune-tm: %.3f [%.3f, %.3f]" % (r["estimate"], *r["interval_95"]))
        md.append("")
        print("k=%d done" % k, flush=True)
    Path(a.output).write_text(json.dumps(out, indent=2) + "\n")
    Path(a.tables).write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
