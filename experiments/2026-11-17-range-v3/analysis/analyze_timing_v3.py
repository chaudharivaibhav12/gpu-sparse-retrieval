"""Paired statistics for Measurement A (run_timing.sh), as registered in configs/protocol.json.

python3 analyze_timing_v3.py RUN --protocol protocol.json --output JSON --tables MD
    [--queries 500 --rounds 20 --warmups 3]

Standard library only. Per process: the median wall latency of each query over the
measured rounds. Process p of one implementation is paired with process p of
another in the same k set. Estimator: geometric mean of the query/process ratios
(pooled over 3 x 500 pairs). Uncertainty: crossed query/process bootstrap,
10,000 draws, 95% percentile interval, seed 20261117. Every quantity is a linear
combination of log medians, so registered ratios and interaction terms share one
bootstrap routine.
Interaction (report item 2): log(v3-all/ctrl) - sum of the single-change log
ratios: k=10 change 1 = v3-1/ctrl, change 2 = v3-2/ctrl (radix is not used at
k=10); k=100 change 1 = v3-1/ctrl, changes 2+3 = v3-3/ctrl (= v3-2/ctrl x v3-3/v3-2).
Crossover (protocol rule): smallest k in {32, 64, 100} whose v3-3/v3-2 upper bound < 1.
"""
import argparse, csv, json, math, random, statistics
from pathlib import Path

SEED, DRAWS, PROCESSES = 20261117, 10000, 3


def per_query_medians(path, queries, rounds, warmups):
    with Path(path).open(newline="") as f:
        rows = list(csv.DictReader(f))
    qids = list(dict.fromkeys(r["query_id"] for r in rows))
    assert len(qids) == queries, path
    wanted = [(ph, str(r), q) for ph, n in (("warmup", warmups), ("measured", rounds)) for r in range(n) for q in qids]
    assert [(r["phase"], r["round"], r["query_id"]) for r in rows] == wanted, "unexpected row order in %s" % path
    wall, gpu = {q: [] for q in qids}, {q: [] for q in qids}
    for r in rows:
        if r["phase"] == "measured":
            w, g = float(r["query_wall_ms"]), float(r["gpu_span_ms"])
            assert math.isfinite(w) and w > 0 and math.isfinite(g) and g > 0
            wall[r["query_id"]].append(w); gpu[r["query_id"]].append(g)
    return qids, [statistics.median(wall[q]) for q in qids], [statistics.median(gpu[q]) for q in qids]


def quantile(ordered, q):
    pos = q * (len(ordered) - 1); lo = int(pos); hi = min(lo + 1, len(ordered) - 1)
    return ordered[lo] + (ordered[hi] - ordered[lo]) * (pos - lo)


def combination(values, coefs, queries):
    """values[name][p][q] medians; coefs {name: c}; returns exp(mean of sum c*log) with bootstrap."""
    logs = [[sum(c * math.log(values[n][p][q]) for n, c in coefs.items()) for q in range(queries)] for p in range(PROCESSES)]
    flat = [v for row in logs for v in row]
    rng = random.Random(SEED); samples = []
    for _ in range(DRAWS):
        ps = rng.choices(range(PROCESSES), k=PROCESSES); qs = rng.choices(range(queries), k=queries)
        sums = [sum(row[q] for q in qs) for row in logs]
        samples.append(math.exp(sum(sums[p] for p in ps) / (PROCESSES * queries)))
    samples.sort()
    return dict(estimate=math.exp(sum(flat) / len(flat)), interval_95=[quantile(samples, .025), quantile(samples, .975)],
                process_estimates=[math.exp(sum(r) / len(r)) for r in logs], pairs_below_1=sum(v < 0 for v in flat), pairs=len(flat))


def ratio(a, b):
    return {a: 1.0, b: -1.0}


def verdict(iv):
    return "faster" if iv[1] < 1 else "slower" if iv[0] > 1 else "no difference resolved"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run"); ap.add_argument("--protocol", required=True); ap.add_argument("--output", required=True); ap.add_argument("--tables", required=True)
    ap.add_argument("--queries", type=int, default=500); ap.add_argument("--rounds", type=int, default=20); ap.add_argument("--warmups", type=int, default=3)
    a = ap.parse_args()
    run, proto = Path(a.run), json.loads(Path(a.protocol).read_text())["measurement_A"]
    out = dict(bootstrap_seed=SEED, bootstrap_draws=DRAWS, processes=PROCESSES, queries=a.queries, measured_rounds=a.rounds, warmup_rounds=a.warmups,
               qualification="Conditional on this cuda5 session, the 500 calibration queries and three processes per implementation. Ratios below 1 favour the numerator.",
               sets={})
    previous = {"10": {"v3-1": "ctrl", "v3-2": "ctrl", "v3-all": "v3-2"},
                "100": {"v3-1": "ctrl", "v3-2": "ctrl", "v3-3": "v3-2", "v3-all": "v3-3"},
                "1000": {"v3-3": "ctrl", "v3-all": "v3-3"}, "32": {"v3-3": "v3-2"}, "64": {"v3-3": "v3-2"}}
    md = ["# Measurement A tables (generated by analyze_timing_v3.py)", ""]
    for key, names in proto["sets"].items():
        k = key.split("=")[1]
        values, gpu, order = {}, {}, None
        for name in names:
            values[name], gpu[name] = [], []
            for p in range(PROCESSES):
                qids, wall, g = per_query_medians(run / "raw" / ("timing-k%s-r%d-%s.csv" % (k, p, name)), a.queries, a.rounds, a.warmups)
                assert order is None or qids == order; order = qids
                values[name].append(wall); gpu[name].append(g)
        s = dict(descriptive={}, contrasts={}, previous_step={})
        for name in names:
            flat = [v for row in values[name] for v in row]
            s["descriptive"][name] = dict(pooled_median_ms=statistics.median(flat), pooled_median_gpu_span_ms=statistics.median(v for row in gpu[name] for v in row),
                                          process_medians_ms=[statistics.median(r) for r in values[name]])
        for c in proto["analysis"]["contrasts"][key]:
            x, y = c.split("/")
            s["contrasts"][c] = combination(values, ratio(x, y), a.queries)
        for name, prev in previous[k].items():
            c = "%s/%s" % (name, prev)
            s["previous_step"][name] = c
            if c not in s["contrasts"]:
                s["contrasts"][c] = combination(values, ratio(name, prev), a.queries)
        if k in ("10", "100"):
            other = "v3-2" if k == "10" else "v3-3"
            coefs = {"v3-all": 1.0, "v3-1": -1.0, other: -1.0, "ctrl": 1.0}
            s["interaction"] = dict(definition="(v3-all/ctrl) / ((v3-1/ctrl) x (%s/ctrl)); 1 = effects multiply" % other,
                                    product_of_single_ratios=s["contrasts"]["v3-1/ctrl"]["estimate"] * (s["contrasts"].get("%s/ctrl" % other) or combination(values, ratio(other, "ctrl"), a.queries))["estimate"],
                                    observed_v3_all_over_ctrl=s["contrasts"]["v3-all/ctrl"]["estimate"],
                                    interaction_ratio=combination(values, coefs, a.queries))
        out["sets"][key] = s
        md += ["## " + key, "", "| variant | pooled median wall (ms) | pooled median GPU span (ms) | ratio to ctrl [95%] | ratio to previous step [95%] |", "|---|---|---|---|---|"]
        for name in names:
            d = s["descriptive"][name]
            rc = s["contrasts"].get("%s/ctrl" % name)
            pc = s["previous_step"].get(name)
            fmt = lambda r: "%.3f [%.3f, %.3f]" % (r["estimate"], *r["interval_95"]) if r else "—"
            md.append("| %s | %.4f | %.4f | %s | %s |" % (name, d["pooled_median_ms"], d["pooled_median_gpu_span_ms"],
                      "1 (reference)" if name == "ctrl" else fmt(rc) if rc else "not in set",
                      ("%s: %s" % (pc, fmt(s["contrasts"][pc]))) if pc else "—"))
        md.append("")
    cross = []
    for k in ("32", "64", "100"):
        r = out["sets"]["k=" + k]["contrasts"]["v3-3/v3-2"]
        cross.append(dict(k=int(k), v3_3_over_v3_2=r["estimate"], interval_95=r["interval_95"], qualifies=r["interval_95"][1] < 1))
    chosen = next((c["k"] for c in cross if c["qualifies"]), None)
    out["crossover"] = dict(rule=proto["analysis"]["crossover_rule"], evidence=cross, recommended_crossover_k=chosen if chosen else 100,
                            note=None if chosen else "radix not shown faster at k <= 100")
    for key, s in out["sets"].items():
        for c, r in s["contrasts"].items():
            r["verdict"] = verdict(r["interval_95"])
    with Path(a.output).open("x") as f:
        json.dump(out, f, indent=2); f.write("\n")
    Path(a.tables).write_text("\n".join(md) + "\n")
    for key, s in out["sets"].items():
        for c, r in s["contrasts"].items():
            print("%-7s %-16s %.4f [%.4f, %.4f] %s" % (key, c, r["estimate"], *r["interval_95"], r["verdict"]))
    print("crossover:", out["crossover"]["recommended_crossover_k"])


if __name__ == "__main__":
    main()
