"""Measurement G3: bandwidth counters and the stage decomposition of u4m (full collection, k=1000).

python3 analyze_g3.py --clocks CLOCKS_JSON [--ncu-raw NCU_RAW_CSV] --output JSON --tables MD

Standard library only. Nsight Compute (25 launches, locked base clocks, caches flushed before each
replayed pass): per launch dram__bytes_read.sum, dram__bytes_write.sum, gpu__dram_throughput (% of
peak), sm__warps_active (achieved occupancy, % of peak), lts__t_sector_hit_rate (L2 hit rate) and
gpu__time_duration; reported as mean (and min-max) over launches, plus bytes / duration.
Clock build (analyze_clocks.py --radix output) mapped onto the paper's categories: allocation/zeroing
= setup (lookup + zero, word-table prefix); traversal = decode+add; top-k = local top-k (radix select
+ gather, bitonic sort, candidate write, threadfence, done ticket) in every range block, plus the
merge (merge select + merge scatter) in the last block only. Range-block shares are of the summed
mean per-block stage times (barrier waits excluded, as in analyze_clocks); the merge is reported on
the wall-clock axis (merge tail / kernel span).
"""
import argparse, csv, json, statistics
from pathlib import Path

UNIT = {"byte": 1, "Kbyte": 1e3, "Mbyte": 1e6, "Gbyte": 1e9, "KB": 1e3, "MB": 1e6, "GB": 1e9}
TIME = {"nsecond": 1e-9, "usecond": 1e-6, "msecond": 1e-3, "ns": 1e-9, "us": 1e-6, "ms": 1e-3}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--clocks", required=True); p.add_argument("--ncu-raw"); p.add_argument("--output", required=True); p.add_argument("--tables", required=True)
    a = p.parse_args()
    c = json.loads(Path(a.clocks).read_text())
    st = {s["stage"]: s for s in c["stages"]}
    # Range blocks (every block runs these) vs the merge (only the last block, once per query).
    RANGE = {"allocation/zeroing (setup)": ["lookup_and_zero", "word_table_prefix"], "traversal (decode+add)": ["decode_add"],
             "local top-k (radix select + gather, bitonic sort, candidate write, fence, ticket)": ["radix_select_gather", "bitonic_sort", "candidate_write", "threadfence", "done_ticket"]}
    MERGE = ["merge_select", "merge_scatter"]   # merge_select = count/scan + compaction + radix select (sub-stages not added again)
    cats = {}
    for name, stages in RANGE.items():
        cats[name] = dict(mean_per_range_block_us=sum(st[x]["mean_per_block_us"] for x in stages), slowest_range_critical_path_us=sum(st[x]["critical_path_us"] for x in stages), stages=stages)
    tot = sum(v["mean_per_range_block_us"] for v in cats.values())
    for v in cats.values():
        v["share_of_range_block_time"] = v["mean_per_range_block_us"] / tot
    merge_us = sum(st[x]["mean_per_block_us"] for x in MERGE)
    span, tail = c["kernel_span_us_median"], c["merge_tail_us_median"]
    out = dict(range_block_categories=cats, merge=dict(last_block_merge_stage_us=merge_us, merge_tail_us_median=tail, share_of_kernel_span=tail / span, stages=MERGE,
                    substages={x: st[x]["mean_per_block_us"] for x in ("merge_count_scan", "merge_compaction", "merge_radix_select") if x in st}),
               kernel_span_us_median=span, range_phase_us=span - tail, sm_clock_ghz=c["sm_clock_ghz_median"],
               blocks_starting_after_first_block_ends_median=c.get("blocks_starting_after_first_block_ends_median"), barrier_warp_time_share=c.get("barrier_warp_time_share"),
               note="Stage times exclude barrier waits (analyze_clocks.py). Range-block shares are of the summed mean per-block stage time, i.e. of the GPU work spread over all range blocks; the merge runs once per query in the last block and is reported on the wall-clock axis (merge tail).")
    md = ["# Measurement G3 tables (generated by analyze_g3.py)", "", "## Stage decomposition (clock build, u4m, full collection, k=1000, 25 calibration queries x 5 rounds)", "",
          "Range blocks (all of them; work spread over the GPU):", "",
          "| paper category | our stages | mean per range block µs | share of range-block time | slowest range block µs |", "|---|---|---|---|---|"]
    for n, v in cats.items():
        md.append("| %s | %s | %.1f | %.1f%% | %.1f |" % (n.split(" (")[0], ", ".join(v["stages"]), v["mean_per_range_block_us"], 100 * v["share_of_range_block_time"], v["slowest_range_critical_path_us"]))
    md += ["", "Merge (top-k, last block only, once per query): merge stages %.1f µs (count/scan %.1f, compaction %.1f, radix select %.1f; scatter %.1f); merge tail %.1f µs = %.1f%% of the kernel span." % (
              merge_us, out["merge"]["substages"].get("merge_count_scan", 0), out["merge"]["substages"].get("merge_compaction", 0), out["merge"]["substages"].get("merge_radix_select", 0), st["merge_scatter"]["mean_per_block_us"], tail, 100 * tail / span),
           "", "Wall clock (globaltimer, median over queries): kernel span %.1f µs = range phase %.1f µs (all range blocks, in waves) + merge tail %.1f µs. SM clock %.2f GHz in the clock build; stage times exclude barrier waits (%.1f%% of warp time)." % (
              span, span - tail, tail, c["sm_clock_ghz_median"], 100 * (c.get("barrier_warp_time_share") or 0))]
    if a.ncu_raw:
        rows = list(csv.reader(open(a.ncu_raw, newline="")))
        head, units, data = rows[0], rows[1], rows[2:]
        col = {n: i for i, n in enumerate(head)}
        def val(r, m):
            x = float(r[col[m]].replace(",", "")); u = units[col[m]].strip()
            return x * UNIT.get(u, TIME.get(u, 1))
        per = []
        for r in data:
            per.append(dict(read=val(r, "dram__bytes_read.sum"), write=val(r, "dram__bytes_write.sum"), dram_pct=val(r, "gpu__dram_throughput.avg.pct_of_peak_sustained_elapsed"),
                            occupancy_pct=val(r, "sm__warps_active.avg.pct_of_peak_sustained_active"), l2_hit_pct=val(r, "lts__t_sector_hit_rate.pct"), seconds=val(r, "gpu__time_duration.sum")))
        agg = {k: dict(mean=statistics.mean(x[k] for x in per), min=min(x[k] for x in per), max=max(x[k] for x in per)) for k in per[0]}
        bw = statistics.mean((x["read"] + x["write"]) / x["seconds"] for x in per)
        out["ncu"] = dict(launches=len(per), per_launch=agg, achieved_dram_bandwidth_gb_s=bw / 1e9)
        md += ["", "## Nsight Compute (u4m, full collection, k=1000, 25 launches; base clocks, caches flushed)", "", "| counter | mean per launch | min - max |", "|---|---|---|"]
        md.append("| DRAM bytes read | %.1f MB | %.1f - %.1f MB |" % (agg["read"]["mean"] / 1e6, agg["read"]["min"] / 1e6, agg["read"]["max"] / 1e6))
        md.append("| DRAM bytes written | %.2f MB | %.2f - %.2f MB |" % (agg["write"]["mean"] / 1e6, agg["write"]["min"] / 1e6, agg["write"]["max"] / 1e6))
        md.append("| DRAM throughput, %% of peak | %.1f%% | %.1f - %.1f%% |" % (agg["dram_pct"]["mean"], agg["dram_pct"]["min"], agg["dram_pct"]["max"]))
        md.append("| achieved occupancy | %.1f%% | %.1f - %.1f%% |" % (agg["occupancy_pct"]["mean"], agg["occupancy_pct"]["min"], agg["occupancy_pct"]["max"]))
        md.append("| L2 hit rate | %.1f%% | %.1f - %.1f%% |" % (agg["l2_hit_pct"]["mean"], agg["l2_hit_pct"]["min"], agg["l2_hit_pct"]["max"]))
        md.append("| kernel duration (ncu) | %.3f ms | %.3f - %.3f ms |" % (agg["seconds"]["mean"] * 1e3, agg["seconds"]["min"] * 1e3, agg["seconds"]["max"] * 1e3))
        md.append("\nAchieved DRAM bandwidth (read + write) / duration: %.0f GB/s (RTX 4070 peak 504 GB/s)." % (bw / 1e9))
    Path(a.output).write_text(json.dumps(out, indent=2) + "\n"); Path(a.tables).write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
