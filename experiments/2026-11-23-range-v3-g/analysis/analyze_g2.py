"""Measurement G2: collection scaling of u4m and ctrl (run_g.sh timing sets).

python3 analyze_g2.py RUN --sizes 100000 1000000 8841823 --output JSON --tables MD [--queries 500 --rounds 20 --warmups 3]

Standard library only; reuses experiments/2026-11-22-range-v3-tune/analysis/analyze_timing_e.py
(per-process per-query medians, crossed bootstrap) with seed 20261124. Per (size, k, scorer):
median, p95 and p99 over the 3 x 500 per-process query medians of query_wall_ms (linear
interpolation; p95/p99 describe query-to-query spread, not a serving tail); ratio u4m / ctrl at
the same size = geometric mean of the paired (process, query) ratios with a crossed bootstrap
(10,000 draws, 95% percentile interval). Growth = median at 8,841,823 / median at 100,000, against
the document ratio 88.42. Index sizes from logs/index-sizes-sha256.tsv; peak GPU memory from
analysis/gpu-memory.json when present (written later in the run; re-run this script to include it).
"""
import argparse, json, math, statistics, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "2026-11-22-range-v3-tune" / "analysis"))
import analyze_timing_e as E   # noqa: E402

E.SEED = 20261124
KS = (10, 100, 1000)
CELLS = ("u4m", "ctrl")
W = {"u4m": 4096, "ctrl": 1024}


def q(v, p):
    v = sorted(v); pos = p * (len(v) - 1); lo = int(pos); hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run"); ap.add_argument("--sizes", nargs="+", type=int, required=True)
    ap.add_argument("--output", required=True); ap.add_argument("--tables", required=True)
    ap.add_argument("--queries", type=int, default=500); ap.add_argument("--rounds", type=int, default=20); ap.add_argument("--warmups", type=int, default=3)
    a = ap.parse_args()
    run = Path(a.run); boot = E.Boot(a.queries)
    idx = {}
    for line in (run / "logs/index-sizes-sha256.tsv").read_text().splitlines():
        s, w, b, h = line.split("\t"); idx[(int(s), int(w))] = dict(bytes=int(b), sha256=h)
    mem = json.loads((run / "analysis/gpu-memory.json").read_text()) if (run / "analysis/gpu-memory.json").exists() else {}
    out = dict(bootstrap_seed=E.SEED, bootstrap_draws=E.DRAWS, sizes={}, qualification="cuda5 RTX 4070; 500 calibration queries; calibration only, after the freeze; conditional on this session and three processes per cell.")
    md = ["# Measurement G2 tables (generated by analyze_g2.py)", "", "Per-query latency (query_wall_ms): median / p95 / p99 over the 3 x 500 per-process query medians; ratio u4m / ctrl at the same size with crossed-bootstrap 95%% interval (seed %d)." % E.SEED, ""]
    md += ["| size | k | u4m median / p95 / p99 ms | ctrl median / p95 / p99 ms | u4m / ctrl [95%] | u4m peak GPU MiB | ctrl peak GPU MiB |", "|---|---|---|---|---|---|---|"]
    for s in a.sizes:
        out["sizes"][str(s)] = dict(index={c: idx.get((s, W[c])) for c in CELLS}, k={})
        for k in KS:
            logs, st = {}, {}
            for c in CELLS:
                rows = []
                for p in range(3):
                    _, wall, _ = E.medians(run / "raw" / ("timing-%d-k%d-r%d-%s.csv" % (s, k, p, c)), a.queries, a.rounds, a.warmups)
                    rows.append([math.log(x) for x in wall])
                logs[c] = rows
                flat = [math.exp(x) for r in rows for x in r]
                peak = max((v.get("peak_used_mib") or 0 for t, v in mem.items() if t.startswith("timing-%d-k%d-" % (s, k)) and t.endswith("-" + c)), default=None)
                st[c] = dict(median_ms=statistics.median(flat), p95_ms=q(flat, 0.95), p99_ms=q(flat, 0.99), peak_gpu_mib=peak or None)
            r = boot.ratio(logs["u4m"], logs["ctrl"])
            out["sizes"][str(s)]["k"][str(k)] = dict(cells=st, ratio_u4m_over_ctrl=r)
            f = lambda d: "%.4f / %.4f / %.4f" % (d["median_ms"], d["p95_ms"], d["p99_ms"])
            md.append("| %s | %d | %s | %s | %.3f [%.3f, %.3f] | %s | %s |" % (format(s, ","), k, f(st["u4m"]), f(st["ctrl"]), r["estimate"], *r["interval_95"], st["u4m"]["peak_gpu_mib"] or "–", st["ctrl"]["peak_gpu_mib"] or "–"))
    if len(a.sizes) > 1:
        lo, hi = str(min(a.sizes)), str(max(a.sizes))
        docs = max(a.sizes) / min(a.sizes)
        g = {c: {str(k): out["sizes"][hi]["k"][str(k)]["cells"][c]["median_ms"] / out["sizes"][lo]["k"][str(k)]["cells"][c]["median_ms"] for k in KS} for c in CELLS}
        out["growth"] = dict(from_size=int(lo), to_size=int(hi), document_ratio=docs, median_latency_ratio=g,
                             paper=dict(latency_growth=85, document_growth=88, batch=500, note="GPUSparse Table 2, batch 500; ours is batch 1"))
        md += ["", "Growth %s -> %s documents (x%.2f): " % (format(int(lo), ","), format(int(hi), ","), docs) + "; ".join("%s k=%d x%.1f" % (c, k, g[c][str(k)]) for c in CELLS for k in KS) + ". Paper: 85x latency over 88x documents at batch 500."]
    md += ["", "Index sizes (bytes): " + "; ".join("%s: u4m W=4096 %s, ctrl W=1024 %s" % (format(s, ","), format(out["sizes"][str(s)]["index"]["u4m"]["bytes"], ","), format(out["sizes"][str(s)]["index"]["ctrl"]["bytes"], ",")) for s in a.sizes if out["sizes"][str(s)]["index"]["u4m"])]
    Path(a.output).write_text(json.dumps(out, indent=2) + "\n"); Path(a.tables).write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
