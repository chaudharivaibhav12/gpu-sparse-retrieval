"""Measurement G2 (amendment 1): collection scaling across three sessions.

python3 analyze_g2_combined.py --cell SIZE RUN U4M_LABEL CTRL_LABEL [--cell ...] --output JSON --tables MD

One --cell per collection size: RUN is a session run folder with uncompressed raw timing CSVs
(raw/timing-k{k}-r{p}-{label}.csv, or raw/timing-{size}-k{k}-r{p}-{label}.csv) and
logs/gpu-poll.log + logs/processes.tsv. Registered cells:
  100000   results/2026-11-23-range-v3-g/<G run>             u4m           ctrl
  1000000  results/2026-11-22-range-v3-tune/20261122-cuda5-timingE-01  v3-4-u4m-w4096  ctrl-w1024
  8841823  results/2026-11-22-range-v3-tune/20261122-cuda5-timingF-01  v3-4-default    ctrl
(E's and F's raw CSVs are on branch exp/arnav/2026-11-22-range-v3-tune at baa3188, gzip.)
All three u4m binaries have CUDA 12.6 SASS 8f8a5d49e0e0ad3f and all three ctrl binaries 53eb3cac16e4bc19.
Per (size, k, scorer): median, p95, p99 over the 3 x 500 per-process query medians of
query_wall_ms (analyze_timing_e.medians; linear-interpolation quantiles); u4m / ctrl within each
session: geometric mean of paired (process, query) ratios, crossed bootstrap 10,000 draws, seed
20261124. Peak GPU memory per process: max over the 3 processes of the nvidia-smi peak
(analyze gpu_memory.py output in RUN/analysis/gpu-memory.json, computed by the caller).
Cross-size comparisons (growth) are descriptive: the sizes come from different sessions.
"""
import argparse, json, math, statistics, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "2026-11-22-range-v3-tune" / "analysis"))
import analyze_timing_e as E   # noqa: E402

E.SEED = 20261124
KS = (10, 100, 1000)


def q(v, p):
    v = sorted(v); pos = p * (len(v) - 1); lo = int(pos); hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def csv_path(run, size, k, p, label):
    for name in ("timing-%d-k%d-r%d-%s.csv" % (size, k, p, label), "timing-k%d-r%d-%s.csv" % (k, p, label)):
        if (run / "raw" / name).exists():
            return run / "raw" / name, name[:-4]
    raise FileNotFoundError("%s k=%d r%d %s in %s" % (size, k, p, label, run))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cell", nargs=4, action="append", required=True, metavar=("SIZE", "RUN", "U4M", "CTRL"))
    ap.add_argument("--output", required=True); ap.add_argument("--tables", required=True)
    a = ap.parse_args()
    boot = E.Boot(500)
    out = dict(bootstrap_seed=E.SEED, bootstrap_draws=E.DRAWS, sizes={},
               qualification="cuda5 RTX 4070; 500 calibration queries; calibration only, after the freeze; each size from its own session, so cross-size comparisons are descriptive")
    for size, run, u_lab, c_lab in a.cell:
        size, run = int(size), Path(run)
        mem = json.loads((run / "analysis/gpu-memory.json").read_text())
        out["sizes"][str(size)] = dict(run=run.name, labels=dict(u4m=u_lab, ctrl=c_lab), k={})
        for k in KS:
            logs, st = {}, {}
            for c, lab in (("u4m", u_lab), ("ctrl", c_lab)):
                rows, peaks = [], []
                for p in range(3):
                    f, tag = csv_path(run, size, k, p, lab)
                    _, wall, _ = E.medians(f, 500, 20, 3)
                    rows.append([math.log(x) for x in wall])
                    peaks.append(mem.get(tag, {}).get("peak_used_mib"))
                logs[c] = rows
                flat = [math.exp(x) for r in rows for x in r]
                st[c] = dict(median_ms=statistics.median(flat), p95_ms=q(flat, 0.95), p99_ms=q(flat, 0.99),
                             peak_gpu_mib=max((x for x in peaks if x), default=None))
            out["sizes"][str(size)]["k"][str(k)] = dict(cells=st, ratio_u4m_over_ctrl=boot.ratio(logs["u4m"], logs["ctrl"]))
    sizes = sorted(int(s) for s in out["sizes"])
    md = ["# Measurement G2 tables (generated by analyze_g2_combined.py)", "",
          "Per-query wall latency, batch 1: median / p95 / p99 (ms) over the 3 x 500 per-process query medians; u4m / ctrl within the same session, crossed-bootstrap 95%% interval (seed %d). Each size is a different session (run named in the table)." % E.SEED, "",
          "| size | run | k | u4m W=4096 median / p95 / p99 | ctrl W=1024 median / p95 / p99 | u4m / ctrl [95%] | peak GPU MiB u4m / ctrl |", "|---|---|---|---|---|---|---|"]
    f = lambda d: "%.4f / %.4f / %.4f" % (d["median_ms"], d["p95_ms"], d["p99_ms"])
    for s in sizes:
        S = out["sizes"][str(s)]
        for k in KS:
            c = S["k"][str(k)]; r = c["ratio_u4m_over_ctrl"]
            md.append("| %s | %s | %d | %s | %s | %.3f [%.3f, %.3f] | %s / %s |" % (format(s, ","), S["run"], k, f(c["cells"]["u4m"]), f(c["cells"]["ctrl"]), r["estimate"], *r["interval_95"], c["cells"]["u4m"]["peak_gpu_mib"], c["cells"]["ctrl"]["peak_gpu_mib"]))
    if len(sizes) > 1:
        lo, hi = sizes[0], sizes[-1]
        g = {c: {str(k): out["sizes"][str(hi)]["k"][str(k)]["cells"][c]["median_ms"] / out["sizes"][str(lo)]["k"][str(k)]["cells"][c]["median_ms"] for k in KS} for c in ("u4m", "ctrl")}
        out["growth_descriptive"] = dict(from_size=lo, to_size=hi, document_ratio=hi / lo, median_latency_ratio=g, paper="85x latency over 88x documents at batch 500 (GPUSparse Table 2)")
        md += ["", "Growth of the median, %s -> %s documents (x%.2f; descriptive, different sessions): " % (format(lo, ","), format(hi, ","), hi / lo) +
               "; ".join("%s k=%d x%.1f" % (c, k, g[c][str(k)]) for c in ("u4m", "ctrl") for k in KS) + ". Paper: 85x latency over 88x documents at batch 500."]
    Path(a.output).write_text(json.dumps(out, indent=2) + "\n"); Path(a.tables).write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
